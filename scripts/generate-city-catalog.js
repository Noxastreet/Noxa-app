#!/usr/bin/env node

/**
 * Generates the offline NOXA city catalog from a local GeoNames dump.
 *
 * Source data (not committed to this repo): GeoNames "cities15000" dataset,
 * "admin1CodesASCII.txt", and "countryInfo.txt", licensed CC BY 4.0
 * (https://www.geonames.org/). Download them from:
 *   https://download.geonames.org/export/dump/cities15000.zip
 *   https://download.geonames.org/export/dump/admin1CodesASCII.txt
 *   https://download.geonames.org/export/dump/countryInfo.txt
 *
 * Usage:
 *   node scripts/generate-city-catalog.js --source <dir-with-raw-files> [--out src/data/cities]
 *
 * <dir-with-raw-files> must contain: cities15000.txt, admin1CodesASCII.txt.
 * countryInfo.txt is not required by this script but is part of the source
 * bundle documented above for provenance.
 *
 * Output: one compact .ts file per ISO2 country code that has catalog data,
 * plus a generated src/data/cityCatalogRegistry.ts loader map. See
 * docs/data-sources/geonames-cities.md for the full data-shape writeup.
 *
 * See docs/data-sources/geonames-cities.md for full attribution and the
 * exact regeneration steps.
 */

const fs = require('fs');
const path = require('path');

function parseArgs(argv) {
  const args = { out: 'src/data/cities' };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--source') args.source = argv[i + 1];
    if (argv[i] === '--out') args.out = argv[i + 1];
  }
  return args;
}

function readCountryCodes(repoRoot) {
  const source = fs.readFileSync(path.join(repoRoot, 'src/data/countryCatalog.ts'), 'utf8');
  const codes = new Set();
  const pattern = /code:\s*'([A-Z]{2})'/g;
  let match = pattern.exec(source);
  while (match) {
    codes.add(match[1]);
    match = pattern.exec(source);
  }
  return codes;
}

function readAdmin1Names(filePath) {
  const map = new Map();
  const lines = fs.readFileSync(filePath, 'utf8').split('\n');
  for (const line of lines) {
    if (!line.trim()) continue;
    const [code, name] = line.split('\t');
    if (code && name) map.set(code, name.trim());
  }
  return map;
}

function readCities(filePath, validCountryCodes) {
  const byCountry = new Map();
  const lines = fs.readFileSync(filePath, 'utf8').split('\n');

  for (const line of lines) {
    if (!line.trim()) continue;
    const fields = line.split('\t');
    const name = fields[1];
    const asciiName = fields[2];
    const countryCode = fields[8];
    const admin1Code = fields[10];
    const population = Number.parseInt(fields[14], 10) || 0;

    if (!name || !countryCode || !validCountryCodes.has(countryCode)) continue;

    if (!byCountry.has(countryCode)) byCountry.set(countryCode, []);
    byCountry.get(countryCode).push({
      name,
      asciiName: asciiName || name,
      population,
      admin1Key: admin1Code ? `${countryCode}.${admin1Code}` : null,
    });
  }

  return byCountry;
}

function attachRegionsForDuplicates(cities, admin1Names) {
  const nameCounts = new Map();
  for (const city of cities) {
    const key = city.name.toLocaleLowerCase();
    nameCounts.set(key, (nameCounts.get(key) || 0) + 1);
  }

  return cities.map((city) => {
    const isDuplicate = nameCounts.get(city.name.toLocaleLowerCase()) > 1;
    const region = isDuplicate && city.admin1Key ? admin1Names.get(city.admin1Key) : undefined;
    return { name: city.name, asciiName: city.asciiName, population: city.population, region };
  });
}

function toRow(city) {
  const tuple = city.region
    ? [city.name, city.asciiName, city.population, city.region]
    : [city.name, city.asciiName, city.population];
  return JSON.stringify(tuple);
}

function writeCountryFile(outDir, countryCode, cities) {
  const sorted = [...cities].sort((a, b) => a.name.localeCompare(b.name, 'en'));
  const rows = sorted.map((city) => `  ${toRow(city)},`).join('\n');
  const contents = `// Generated by scripts/generate-city-catalog.js from GeoNames "cities15000" (CC BY 4.0).
// See docs/data-sources/geonames-cities.md. Do not edit by hand — regenerate instead.
export const cities = [
${rows}
] as const;
`;
  fs.writeFileSync(path.join(outDir, `${countryCode}.ts`), contents);
}

function writeRegistry(repoRoot, countryCodes) {
  const sorted = [...countryCodes].sort();
  const loaderLines = sorted.map((code) => `  ${code}: () => require('./cities/${code}').cities,`).join('\n');
  const contents = `// Generated by scripts/generate-city-catalog.js. Do not edit by hand — regenerate instead.
// Explicit static loader registry: Metro cannot resolve a fully dynamic
// require(), and eagerly importing every country file would parse and
// evaluate all of them at startup. Each entry below is a literal require()
// Metro can statically resolve, wrapped in a function so the module body
// only executes the first time that country's catalog is actually loaded.

export type CityRecord = readonly [name: string, asciiName: string, population: number, region?: string];

type CityLoader = () => readonly CityRecord[];

const loaders: Record<string, CityLoader> = {
${loaderLines}
};

export function hasCityCatalog(countryCode: string): boolean {
  return Object.prototype.hasOwnProperty.call(loaders, countryCode.toUpperCase());
}

export function loadCityCatalogRaw(countryCode: string): readonly CityRecord[] {
  const loader = loaders[countryCode.toUpperCase()];
  return loader ? loader() : [];
}
`;
  fs.writeFileSync(path.join(repoRoot, 'src/data/cityCatalogRegistry.ts'), contents);
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.source) {
    console.error('Usage: node scripts/generate-city-catalog.js --source <dir-with-raw-files> [--out src/data/cities]');
    process.exit(1);
  }

  const repoRoot = path.resolve(__dirname, '..');
  const outDir = path.resolve(repoRoot, args.out);
  fs.mkdirSync(outDir, { recursive: true });

  const validCountryCodes = readCountryCodes(repoRoot);
  const admin1Names = readAdmin1Names(path.join(args.source, 'admin1CodesASCII.txt'));
  const byCountry = readCities(path.join(args.source, 'cities15000.txt'), validCountryCodes);

  const generatedCountryCodes = [];
  let totalCities = 0;

  for (const [countryCode, cities] of [...byCountry.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const resolved = attachRegionsForDuplicates(cities, admin1Names);
    writeCountryFile(outDir, countryCode, resolved);
    generatedCountryCodes.push(countryCode);
    totalCities += resolved.length;
  }

  writeRegistry(repoRoot, generatedCountryCodes);

  const missing = [...validCountryCodes].filter((code) => !byCountry.has(code)).sort();
  console.log(`Generated ${generatedCountryCodes.length} country files, ${totalCities} cities total.`);
  console.log(`Countries with no catalog data (${missing.length}): ${missing.join(', ')}`);
}

main();
